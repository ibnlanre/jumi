/**
 * Creates a generator for a single-property keyframe.
 *
 * Every animatable property follows the same pattern: a `@keyframes` block
 * whose `to` state reads the property's Jumi CSS variable:
 *
 *   @keyframes <animationName> { to { <property>: var(--jumi-<property>) } }
 *
 * The property names are driven by data (property + value), so passing a
 * computed `animationName` yields a unique keyframe for each distinct value
 * (see `property()` in the creator, which suffixes a stable short id).
 */
function propertyKeyframe(attribute: string) {
  return (animationName: string) => ({
    [`@keyframes ${animationName}`]: {
      to: {
        [attribute]: css('var', `--jumi-${attribute}`),
      },
    },
  })
}

